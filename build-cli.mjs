#!/usr/bin/env node
/**
 * CLI 번들 — src/cli/main.ts → dist-cli/harness.mjs (단일 ESM, 의존성 0).
 *
 *  · jsPDF 까지 한 파일에 묶는다. `@napi-rs/canvas`(한글 래스터, 네이티브)만 밖에 둔다 —
 *    있으면 쓰고 없으면 경고 한 줄(src/cli/nodeCanvas.ts).
 *  · `@xyflow/react` 는 Position enum 하나만 쓰므로 src/cli/xyflow-shim.ts 로 갈아끼운다
 *    (React·d3 가 딸려 오지 않게).
 *  · 데이터시트 캡처(public/datasheets/*.png, 합계 0.5MB 안쪽)는 data URL 로 번들에
 *    심는다 — PDF 부록이 네트워크·파일 없이 나온다.
 *  · 결과를 bin/harness.mjs(저장소 · npm bin)와 public/harness.mjs(GitHub Pages:
 *    https://qpwo5470.github.io/harness-tool/harness.mjs)에 복사한다.
 */
import { build } from 'esbuild';
import { readFileSync, readdirSync, mkdirSync, copyFileSync, chmodSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

const dsDir = join(root, 'public', 'datasheets');
const datasheets = {};
for (const f of readdirSync(dsDir)) {
  if (!/\.(png|jpe?g)$/i.test(f)) continue;
  const mime = /\.png$/i.test(f) ? 'image/png' : 'image/jpeg';
  datasheets[`datasheets/${f}`] = `data:${mime};base64,${readFileSync(join(dsDir, f)).toString('base64')}`;
}

const out = join(root, 'dist-cli', 'harness.mjs');
mkdirSync(dirname(out), { recursive: true });

await build({
  entryPoints: [join(root, 'src', 'cli', 'main.ts')],
  outfile: out,
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node18',
  minify: true,
  legalComments: 'none',
  charset: 'utf8',
  alias: { '@xyflow/react': join(root, 'src', 'cli', 'xyflow-shim.ts') },
  // jsPDF 의 html()·svg 경로만 쓰는 선택 의존성 — CLI 는 부르지 않는다
  external: ['@napi-rs/canvas', 'canvg', 'html2canvas', 'dompurify'],
  define: {
    __HARNESS_DATASHEETS__: JSON.stringify(datasheets),
    __HARNESS_CLI_VERSION__: JSON.stringify(pkg.version),
    'import.meta.env': '{}',
  },
  banner: {
    js: [
      '#!/usr/bin/env node',
      '// harness CLI + JS API — https://qpwo5470.github.io/harness-tool/harness.mjs (generated by build-cli.mjs; do not edit)',
      "import { createRequire as __harnessCreateRequire } from 'node:module';",
      'const require = __harnessCreateRequire(import.meta.url);',
    ].join('\n'),
  },
  logLevel: 'warning',
});

chmodSync(out, 0o755);
for (const dest of [join(root, 'bin', 'harness.mjs'), join(root, 'public', 'harness.mjs')]) {
  mkdirSync(dirname(dest), { recursive: true });
  copyFileSync(out, dest);
  chmodSync(dest, 0o755);
}
console.log(`dist-cli/harness.mjs ${(statSync(out).size / 1024).toFixed(0)}KB → bin/harness.mjs, public/harness.mjs`);
